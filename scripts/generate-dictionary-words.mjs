#!/usr/bin/env node
/**
 * Writes src/generated/common-words.ts: the common English words dictation corrections never
 * touch (src/lib/dictionary/words.ts), from SCOWL (http://wordlist.aspell.net, release
 * 2020.12.07): English and American words, capitalized words (Monday, Paris) and proper names
 * (ordinary names) up to size 50, the size of a typical spell checker's list.
 * Lowercase ASCII letters only, possessives dropped, sorted and front-coded: each word is
 * one character for the length of the prefix it shares with the previous word ('0'-'9', then
 * 'A'-'Z' for 10-35), followed by the rest of the word.
 *
 *   curl -LO https://downloads.sourceforge.net/wordlist/scowl-2020.12.07.tar.gz && tar xzf scowl-2020.12.07.tar.gz
 *   node scripts/generate-dictionary-words.mjs scowl-2020.12.07
 *
 * SCOWL's copyright and permission notice is in src/lib/dictionary/SCOWL-COPYRIGHT (shown in
 * THIRD_PARTY_NOTICES.md by scripts/generate-notices.mjs).
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const scowl = process.argv[2];
if (!scowl) {
  console.error('usage: node scripts/generate-dictionary-words.mjs <scowl-2020.12.07 directory>');
  process.exit(1);
}

const lists = [];
for (const size of [10, 20, 35, 40, 50]) {
  for (const kind of ['words', 'upper', 'proper-names']) lists.push(`english-${kind}.${size}`, `american-${kind}.${size}`);
}

const words = new Set();
for (const name of lists) {
  const file = join(scowl, 'final', name);
  if (!existsSync(file)) continue;
  // SCOWL is ISO-8859-1; anything outside a-z is dropped below anyway.
  for (const line of readFileSync(file, 'latin1').split('\n')) {
    const w = line.trim().toLowerCase();
    if (/^[a-z]+$/.test(w)) words.add(w);
  }
}

const sorted = [...words].sort();
let prev = '';
let out = '';
for (const w of sorted) {
  let p = 0;
  while (p < 35 && p < prev.length && p < w.length && prev[p] === w[p]) p += 1;
  out += (p < 10 ? String.fromCharCode(48 + p) : String.fromCharCode(55 + p)) + w.slice(p);
  prev = w;
}

const target = join(root, 'src/generated/common-words.ts');
writeFileSync(
  target,
  `// Generated by scripts/generate-dictionary-words.mjs from SCOWL 2020.12.07 (words, capitalized\n` +
    `// words and proper names up to size 50; copyright notice in src/lib/dictionary/SCOWL-COPYRIGHT). Do not edit.\n` +
    `// ${sorted.length} words, front-coded (see the script).\n\n` +
    `export const COMMON_WORDS_FRONT_CODED =\n  ${JSON.stringify(out)};\n`,
);
console.log(`wrote ${target}: ${sorted.length} words, ${out.length} chars`);
